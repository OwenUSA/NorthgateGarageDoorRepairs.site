// Emits assets/INVENTORY.md from .harness/inventory.json. Regenerate, never hand-edit
// the table — this module only knows how to build the table. Any site-specific narrative
// (font investigations, video tables, badge notes, decision-register references...) is
// NOT this module's business: it belongs in optional per-site fragments,
// assets/INVENTORY.head.md and assets/INVENTORY.tail.md, read verbatim and sandwiched
// around the generated table if those files exist.
//   node src/write-inventory.mjs
import path from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { ensure } from './lib.mjs';
import { loadConfig } from './config.mjs';

async function readFragment(file) {
  return existsSync(file) ? readFile(file, 'utf8') : '';
}

function dim(r, b) { return r.bps[b] ? `${r.bps[b].w}x${r.bps[b].h}` : '—'; }
function ph(generated, id) {
  return generated.filter((g) => g.slotId === id).map((g) => path.basename(g.file)).join(' + ') || '—';
}

function buildTable(d, bps) {
  const rows = d.rows;
  const bpHead = bps.map((b) => String(b)).join(' | ');
  const head = `| slot ID | route | section | kind | ${bpHead} | aspect | object-fit | dominant | aspect Δ | placeholder |\n` +
    `|---|---|---|---|${bps.map(() => '---').join('|')}|---|---|---|---|---|`;
  const canonical = Math.max(...bps);
  const body = rows
    .filter((r) => r.provenance === 'REPLACE')
    .map((r) => `| \`${r.slotId}\` | ${r.route} | ${r.section} | ${r.kind} | ${bps.map((b) => dim(r, b)).join(' | ')} | ${r.aspects[canonical] ?? '-'} | ${r.objectFit} | \`${r.colour.hex}\` | ${r.aspectChanges ? '**yes**' : 'no'} | \`${ph(d.generated, r.slotId)}\` |`)
    .join('\n');

  const deleted = rows.filter((r) => r.provenance === 'DELETED')
    .map((r) => `| \`${r.slotId}\` | ${r.route} | ${r.section} | ${dim(r, canonical)} | ${r.note} |`)
    .join('\n');

  const tally = [
    '| | count |',
    '|---|---|',
    `| slots inventoried | ${rows.length} |`,
    `| REPLACE | ${rows.filter((r) => r.provenance === 'REPLACE').length} |`,
    `| DELETED | ${rows.filter((r) => r.provenance === 'DELETED').length} |`,
    `| placeholders generated | ${d.generated.length} |`,
    `| REPLACE assets downloaded | **0** |`,
  ].join('\n');

  return `## REPLACE — every slot, with the geometry a generator needs\n\n${head}\n${body}\n\n` +
    `## DELETED — inventoried, deliberately not filled\n\n` +
    `| slot ID | route | section | ${canonical} | why |\n|---|---|---|---|---|\n${deleted}\n\n` +
    `## Tally\n\n${tally}\n`;
}

async function main() {
  const cfg = await loadConfig();
  const invFile = path.join(cfg.harnessDir, 'inventory.json');
  if (!existsSync(invFile)) {
    console.error(`no ${invFile} — run inventory.mjs first`);
    process.exitCode = 1;
    return;
  }
  const d = JSON.parse(await readFile(invFile, 'utf8'));
  const bps = cfg.breakpoints.diff;

  const assetsDir = path.join(cfg.siteRoot, 'assets');
  const head = await readFragment(path.join(assetsDir, 'INVENTORY.head.md'));
  const tail = await readFragment(path.join(assetsDir, 'INVENTORY.tail.md'));

  const generatedHead = head || [
    '# assets/INVENTORY.md — asset slots, provenance, status',
    '',
    'Generated by `src/inventory.mjs` from `.harness/assets/*.json` and `.harness/cap/ref/**/sec-*.png`.',
    'Machine-readable inventory: `.harness/inventory.json`.',
    '',
  ].join('\n');

  const table = buildTable(d, bps);
  const out = `${generatedHead}\n${table}\n${tail}`;

  await ensure(assetsDir);
  await writeFile(path.join(assetsDir, 'INVENTORY.md'), out, 'utf8');
  console.log('assets/INVENTORY.md written:', out.length, 'bytes', head ? '(with head fragment)' : '', tail ? '(with tail fragment)' : '');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
